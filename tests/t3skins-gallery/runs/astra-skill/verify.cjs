const {chromium} = require('/tmp/bunx-1001-playwright@latest/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = '/home/shrikant/programing-vm/ui-bench/tests/t3skins-gallery/runs/astra-skill';
let browser;
(async () => {
  browser = await chromium.launch({headless:true,executablePath:'/home/shrikant/.cache/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-linux64/chrome-headless-shell',downloadsPath:path.join(root,'.browser-tmp')});
  const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror',e => errors.push(e.message));
  page.on('console',m => {if(m.type()==='error') errors.push(m.text());});
  const results = [];
  const check = (name,condition) => {assert.ok(condition,name);results.push({name,pass:true});};
  await context.setOffline(true);
  await page.goto('file://'+path.join(root,'index.html'));
  await page.locator('.card').last().waitFor({state:'attached'});
  await page.evaluate(() => document.fonts.ready);
  check('Offline file:// renders all 78 skins',await page.locator('.card').count()===78);
  check('Offline fonts load',await page.evaluate(() => [...document.fonts].every(f=>f.status==='loaded')));
  check('Offline featured preview loads',await page.locator('#featured-preview iframe').evaluate(frame=>frame.contentDocument?.querySelector('.shell')!==null));
  await page.screenshot({path:path.join(root,'desktop-review.png')});
  await page.locator('.card [data-save="nyx"]').click();
  await page.reload();
  check('Saved skins persist on file:// reload',await page.locator('#saved-count').innerText()==='1');
  await page.locator('.library-tabs [data-library="saved"]').click();
  check('Offline saved collection',await page.locator('.card').count()===1);
  await page.locator('.card [data-save="nyx"]').click();
  await page.locator('.empty [data-library="all"]').click();
  await page.locator('#search').fill('T3 Clawd');
  await page.locator('.card [data-mode="light"]').click();
  await page.locator('.card .preview-link').click();
  check('Offline details and light mode',await page.locator('#details iframe').evaluate(frame=>frame.srcdoc.includes('color-scheme:light')));
  await page.keyboard.press('Escape');
  const downloadPromise=page.waitForEvent('download');
  await page.locator('.card a[download]').click();
  const download=await downloadPromise;
  await download.saveAs(path.join(root,'.browser-tmp','downloaded.json'));
  const downloaded=JSON.parse(fs.readFileSync(path.join(root,'.browser-tmp','downloaded.json'),'utf8'));
  check('Offline JSON download',download.suggestedFilename()==='t3-clawd.json'&&typeof downloaded==='object');
  await page.locator('#search').fill('');
  await page.setViewportSize({width:360,height:800});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  check('360 px page has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  await page.screenshot({path:path.join(root,'mobile-review.png')});
  await page.locator('.mobile-filters').click();
  await page.locator('[data-filter="appearance"][data-value="light"]').click();
  check('Mobile filter controls work',await page.locator('.card').count()===30);
  await page.locator('.reset-button').click();
  await page.locator('.mobile-filters').click();
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('.card .motion-paused').first().waitFor();
  check('Reduced motion pauses every animated live preview',await page.locator('.card .motion-paused').count()===39);
  await page.locator('#search').fill('Nebula');
  await page.locator('[data-play="nebula"]').click();
  check('Reduced-motion preview can be shown explicitly',await page.locator('.card[data-id="nebula"] iframe').count()===1);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.locator('#search').fill('');
  await page.setViewportSize({width:768,height:1024});
  check('768 px page has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  await page.setViewportSize({width:1024,height:768});
  check('1024 px page has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  await page.setViewportSize({width:1440,height:1000});
  for (const frame of await page.locator('#grid iframe').all()) await frame.evaluate(el=>el.loading='eager');
  await page.waitForFunction(()=>[...document.querySelectorAll('#grid iframe')].every(f=>f.contentDocument?.querySelector('.shell')));
  check('All 74 live mock previews load',await page.locator('#grid iframe').count()===74);
  await page.locator('#grid img').evaluateAll(images=>images.forEach(i=>i.loading='eager'));
  await page.waitForFunction(()=>[...document.querySelectorAll('#grid img')].every(i=>i.complete&&i.naturalWidth>0));
  check('All 4 image previews load',await page.locator('#grid img').evaluateAll(images=>images.length===4&&images.every(i=>i.complete&&i.naturalWidth>0)));
  check('No browser console or runtime errors',errors.length===0);
  const report={results,errors};
  fs.writeFileSync(path.join(root,'verification.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  await browser.close();
})().catch(async e=>{console.error(e);await browser?.close();process.exitCode=1;});
